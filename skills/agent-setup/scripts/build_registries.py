#!/usr/bin/env python3
"""Build REGISTRY.md from document metadata; never use the output as input.

Portable adaptation of a metadata-driven registry generator from a working PM
workspace. Each directory has a registry.yaml; PyYAML is the only dependency.
"""

from __future__ import annotations

import argparse
import datetime as dt
import difflib
import fnmatch
import hashlib
import json
import os
import re
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import quote, unquote

try:
    import yaml
except ImportError:
    raise SystemExit("PyYAML is required; install scripts/requirements.txt in the project environment")

from workspace_paths import files, inside, rewrite_links

SKIP_PARTS = {".git", "Archive", "archive", "_archive", "node_modules", ".venv", "__pycache__"}
GENERATED = "<!-- Generated by build_registries.py; edit source metadata. -->"


class RegistryError(ValueError):
    """Invalid source data; no output may be written."""


class UniqueLoader(yaml.SafeLoader):
    """A duplicate key must not silently discard registry information."""


def unique_mapping(loader: UniqueLoader, node: yaml.MappingNode) -> dict:
    result = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=True)
        if key in result:
            raise RegistryError(f"duplicate YAML key: {key}")
        result[key] = loader.construct_object(value_node, deep=True)
    return result


UniqueLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, unique_mapping)


def mapping(text: str, source: Path) -> dict:
    try:
        value = yaml.load(text, Loader=UniqueLoader)
    except (yaml.YAMLError, RegistryError, TypeError) as exc:
        raise RegistryError(f"{source}: {exc}") from exc
    if value is None:
        return {}
    if not isinstance(value, dict):
        raise RegistryError(f"{source}: expected a YAML mapping")
    return value


def document(path: Path) -> dict:
    text = path.read_text(encoding="utf-8-sig")
    lines = text.splitlines()
    data: dict = {}
    if lines and lines[0] == "---":
        end = next((i for i in range(1, len(lines)) if lines[i] == "---"), None)
        if end is None:
            raise RegistryError(f"{path}: unclosed frontmatter")
        data = mapping("\n".join(lines[1:end]), path)
        lines = lines[end + 1:]
    # A heading inside an example is not the document title.
    fence = None
    for line in lines:
        match = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if match:
            marker = match.group(1)
            if fence is None:
                fence = marker
            elif marker[0] == fence[0] and len(marker) >= len(fence):
                fence = None
            continue
        if fence is None and (match := re.match(r"^#\s+(.+?)\s*#*\s*$", line)):
            if not data.get("title"):
                data["title"] = match.group(1)
            break
    return data


def lookup(data: dict, key: str) -> Any:
    value: Any = data
    for part in key.split("."):
        if not isinstance(value, dict) or part not in value:
            return None
        value = value[part]
    return value


def scalar(value: Any) -> str:
    if value is None or value == "":
        return "—"
    if isinstance(value, (dt.datetime, dt.date)):
        return value.isoformat()
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (list, tuple)):
        return ", ".join(scalar(item) for item in value) or "—"
    if isinstance(value, dict):
        return "; ".join(f"{key}: {scalar(item)}" for key, item in value.items()) or "—"
    return str(value)


def cell(value: Any) -> str:
    # Preserve existing Markdown, including already escaped pipes.
    return re.sub(r"(?<!\\)\|", r"\|", scalar(value)).replace("\r\n", "\n").replace("\n", "<br>")


def within(base: Path, relative: str) -> Path:
    if not isinstance(relative, str) or Path(relative).is_absolute():
        raise RegistryError(f"{base}: expected a relative path: {relative!r}")
    path = base / relative
    if not path.resolve().is_relative_to(base.resolve()):
        raise RegistryError(f"{base}: path escapes source directory: {relative}")
    return path


@dataclass
class Entry:
    path: str
    data: dict
    origins: dict[str, Path]


def rebase_links(text: str, source: Path, destination: Path) -> str:
    return rewrite_links(text, source / "_metadata.md", destination / "_registry.md")


def enrich(path: str, data: dict) -> dict:
    result = dict(data)
    result["path"] = path
    result["name"] = Path(path).name
    result["section"] = Path(path).parent.as_posix()
    return result


def excluded(relative: Path, patterns: list[str]) -> bool:
    return bool(SKIP_PARTS.intersection(relative.parts)) or any(
        fnmatch.fnmatchcase(relative.as_posix(), pattern) for pattern in patterns
    )


def validate_table(table: dict) -> None:
    for key in ('include', 'exclude', 'sort'):
        if key in table and (not isinstance(table[key], list) or not all(isinstance(v, str) for v in table[key])):
            raise RegistryError(f'{key} must be a list of strings')
    if not isinstance(table.get('records', []), list) or not isinstance(table.get('where', {}), dict):
        raise RegistryError('records must be a list; where must be a mapping')
    for column in table.get('columns', []):
        if not isinstance(column, dict):
            raise RegistryError('column must be a mapping')
        if 'fallback' in column and not isinstance(column['fallback'], str):
            raise RegistryError('fallback must be a field name')
        for key in ('link', 'required'):
            if key in column and not isinstance(column[key], bool):
                raise RegistryError(f'{key} must be boolean')


def entries(base: Path, table: dict, root: Path) -> list[Entry]:
    validate_table(table)
    found: dict[str, Entry] = {}
    for pattern in table.get("include", []):
        if not isinstance(pattern, str) or pattern.startswith("/") or ".." in Path(pattern).parts:
            raise RegistryError(f"{base}: invalid include pattern {pattern!r}")
        for path in sorted(base.glob(pattern)):
            relative = path.relative_to(base)
            if not path.is_file() or excluded(relative, table.get("exclude", [])):
                continue
            within(base, relative.as_posix())  # also reject external symlinks
            if path.name == "REGISTRY.md":
                continue
            if path.suffix.lower() != ".md":
                raise RegistryError(f"{path}: non-Markdown files need explicit metadata")
            data = document(path)
            if lookup(data, "registry.exclude") is True:
                continue
            data = enrich(relative.as_posix(), data)
            found[relative.as_posix()] = Entry(relative.as_posix(), data, {key: path.parent for key in data})

    # Explicit records describe scripts, attachments, directories or immutable
    # publications. Mutable Markdown uses frontmatter instead of shadow copies.
    for record in table.get("records", []):
        if not isinstance(record, dict) or not isinstance(record.get("path"), str):
            raise RegistryError(f"{base}: record needs a path")
        relative = record["path"]
        if Path(relative).is_absolute():
            raise RegistryError("record path must be relative")
        # A section can catalog a repository-level utility (e.g. ../sync-claude.sh),
        # but cannot read sources outside the repository.
        path = inside(root, os.path.relpath(base / relative, root))
        if not path.exists() and not record.get("unavailable"):
            raise RegistryError(f"{path}: missing source; mark unavailable with an explanation")
        if record.get("unavailable") and not isinstance(record["unavailable"], str):
            raise RegistryError(f"{path}: unavailable must explain the missing source")
        data = document(path) if path.is_file() and path.suffix.lower() == ".md" else {}
        metadata = {key: value for key, value in record.items() if key not in {"path", "key"}}
        origins = {key: path.parent for key in data}
        for key in data.keys() & metadata.keys():
            if data[key] != metadata[key]:
                raise RegistryError(f"{path}: metadata conflicts with frontmatter field {key}")
        data.update(metadata)
        origins.update({key: base for key in metadata})
        identity = record.get("key", relative)
        if identity in found:
            raise RegistryError(f"{path}: duplicate source (include and records)")
        found[identity] = Entry(relative, enrich(relative, data), origins)

    result = list(found.values())
    where = table.get("where", {})
    if where:
        result = [entry for entry in result if all(
            lookup(entry.data, key) in value if isinstance(value, list) else lookup(entry.data, key) == value
            for key, value in where.items()
        )]
    sort = table.get("sort", ["path"])
    if not isinstance(sort, list) or not all(isinstance(key, str) for key in sort):
        raise RegistryError(f"{base}: sort must be a list of field names")
    return sorted(result, key=lambda entry: tuple(
        scalar(entry.path if key == "path" else lookup(entry.data, key)) for key in sort
    ) + (entry.path,))


def render_table(base: Path, table: dict, root: Path, destination: Path) -> tuple[str, int]:
    columns = table.get("columns")
    if not isinstance(columns, list) or not columns:
        raise RegistryError(f"{base}: table needs columns")
    for column in columns:
        if not isinstance(column, dict) or not all(isinstance(column.get(key), str) for key in ("label", "field")):
            raise RegistryError(f"{base}: each column needs label and field")
    rows = entries(base, table, root)
    output = ["| " + " | ".join(cell(column["label"]) for column in columns) + " |",
              "| " + " | ".join("---" for _ in columns) + " |"]
    for entry in rows:
        values = []
        for column in columns:
            field = column["field"]
            value = entry.path if field == "path" else lookup(entry.data, field)
            if value is None and column.get("fallback"):
                value = lookup(entry.data, column["fallback"])
            if column.get("required") and (value is None or value == ""):
                raise RegistryError(f"{base / entry.path}: missing required field {field}")
            if column.get("link"):
                label = scalar(value) if value is not None else Path(entry.path).name
                target = quote(os.path.relpath(base / entry.path, destination).replace(os.sep, "/"), safe="/-._~")
                label = label.replace("[", r"\[").replace("]", r"\]")
                value = f"[{label}]({target})"
            else:
                value = rebase_links(scalar(value), entry.origins.get(field.split('.')[0], base), destination)
            values.append(cell(value))
        output.append("| " + " | ".join(values) + " |")
    if not rows:
        output.append("| " + " | ".join("—" for _ in columns) + " |")
    heading = table.get("heading")
    return ((f"## {heading}\n\n" if heading else "") + "\n".join(output), len(rows))


def render(config: Path, root: Path, destination: Path) -> tuple[str, int]:
    spec = mapping(config.read_text(encoding="utf-8"), config)
    if spec.get("version") != 1:
        raise RegistryError(f"{config}: expected version: 1")
    if not isinstance(spec.get("title"), str) or not isinstance(spec.get("tables"), list):
        raise RegistryError(f"{config}: title and tables are required")
    parts = [GENERATED, f"# {spec['title']}"]
    if spec.get("intro"):
        parts.append(spec["intro"].strip())
    count = 0
    for table in spec["tables"]:
        if not isinstance(table, dict):
            raise RegistryError(f"{config}: table must be a mapping")
        table = dict(table)
        validate_table(table)
        if any((config.parent / record.get("path", "")).resolve() == destination.resolve() for record in table.get("records", []) if isinstance(record, dict)):
            raise RegistryError("generated output cannot be a records source")
        table["exclude"] = list(table.get("exclude", [])) + [os.path.relpath(destination, config.parent).replace(os.sep, "/")]
        content, size = render_table(config.parent, table, root, destination.parent)
        parts.append(content)
        count += size
    for name in spec.get("notes", []):
        path = within(config.parent, name)
        if path.resolve() == destination.resolve():
            raise RegistryError(f"{config}: generated output cannot be a source")
        if not path.is_file():
            raise RegistryError(f"{path}: missing notes file")
        parts.append(f"Notes: [{name}]({quote(os.path.relpath(path, destination.parent).replace(os.sep, "/"), safe='/-._~')}).")
    return "\n\n".join(parts).rstrip() + "\n", count


START, END = '<!-- registry:start -->', '<!-- registry:end -->'


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', newline='', dir=path.parent, delete=False) as tmp:
        tmp.write(text)
        temporary = Path(tmp.name)
    try:
        if path.exists():
            temporary.chmod(path.stat().st_mode & 0o777)
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def make_output(config: Path, root: Path):
    spec = mapping(config.read_text(encoding='utf-8'), config)
    if not isinstance(spec.get('output', 'REGISTRY.md'), str) or not isinstance(spec.get('section', False), bool):
        raise RegistryError('output must be a relative path; section must be boolean')
    if 'intro' in spec and not isinstance(spec['intro'], str):
        raise RegistryError('intro must be text')
    if not isinstance(spec.get('notes', []), list) or not all(isinstance(v, str) for v in spec.get('notes', [])):
        raise RegistryError('notes must be a list of paths')
    if Path(spec.get('output', 'REGISTRY.md')).is_absolute():
        raise RegistryError('output must be relative')
    output = inside(root, os.path.relpath(config.parent / spec.get('output', 'REGISTRY.md'), root))
    if output.suffix.lower() != '.md' or output == config:
        raise RegistryError('Output must be a Markdown file')
    before = output.read_bytes().decode('utf-8') if output.exists() else None
    content, count = render(config, root, output)
    if spec.get('section') is True:
        if before is None or before.count(START) != 1 or before.count(END) != 1:
            raise RegistryError(f'{output}: section mode needs exactly one start/end marker pair')
        start, end = before.index(START) + len(START), before.index(END)
        if start >= end:
            raise RegistryError(f'{output}: reversed markers')
        content = before[:start] + '\n\n' + content.rstrip() + '\n\n' + before[end:]
    elif before and not before.startswith(GENERATED):
        raise RegistryError(f'{output}: refusing to overwrite a manual file; use section markers or migrate its content first')
    return output, before, content, count


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--config', action='append', help='Root-relative registry.yaml; repeat for selected scopes')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='Read-only drift check; exit 1 for stale output')
    mode.add_argument('--apply', action='store_true', help='Write generated outputs; default previews only')
    parser.add_argument('--diff', action='store_true', help='Show diff also in check/apply mode')
    args = parser.parse_args(argv)
    try:
        root = args.root.resolve()
        if not root.is_dir():
            raise RegistryError('Root must exist')
        sources = [inside(root, name) for name in args.config] if args.config else [
            p for p in files(root) if p.name == 'registry.yaml' and not SKIP_PARTS.intersection(p.relative_to(root).parts)]
        if not sources or len(set(sources)) != len(sources):
            raise RegistryError('Need distinct registry.yaml configurations')
        # Fully validate/render before touching any output.
        outputs = [make_output(config, root) for config in sources]
        targets = [item[0] for item in outputs]
        if len(set(targets)) != len(targets):
            raise RegistryError('Multiple configurations target the same output')
        changed = [(p, old, new, size) for p, old, new, size in outputs if old != new]
        for path, before, after, count in outputs:
            print(f'{"STALE" if before != after else "OK"} {path.relative_to(root)}: {count} entries')
            if before != after and (args.diff or not (args.check or args.apply)):
                sys.stdout.writelines(difflib.unified_diff((before or '').splitlines(True), after.splitlines(True),
                                                         fromfile=path.relative_to(root).as_posix(), tofile=path.relative_to(root).as_posix()))
        if args.apply:
            written = []
            try:
                for path, before, after, _ in changed:
                    current = path.read_bytes().decode('utf-8') if path.exists() else None
                    if current != before:
                        raise RegistryError(f'{path}: output changed after planning')
                    written.append((path, before))
                    atomic_write(path, after)
            except Exception:
                for path, before in reversed(written):
                    if before is None:
                        path.unlink(missing_ok=True)
                    else:
                        atomic_write(path, before)
                raise
        print(f'{len(outputs)} registries; {len(changed)} differences; ' + ('APPLIED' if args.apply else 'READ-ONLY'))
        return 1 if args.check and changed else 0
    except (ValueError, OSError, TypeError, KeyError, UnicodeError) as exc:
        print(f'ERROR: {exc}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
